class Translator:
    def __init__(self, lang='zh'):
        self.lang = lang
        self.translations = TRANSLATIONS
    
    def set_lang(self, lang):
        if lang in self.translations:
            self.lang = lang
    
    def t(self, key):
        return self.translations.get(self.lang, {}).get(key, key)
    
    def get_available_languages(self):
        return [
            ('en', 'English'),
            ('zh', '中文')
        ]


